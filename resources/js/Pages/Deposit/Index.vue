async function submitInvoice() {
    invoiceErrors.value = {};
    const amt = Number(invoiceAmount.value);

    if (!Number.isFinite(amt) || amt <= 0) {
        invoiceErrors.value.amount = 'Deposit amount is required.';
        return;
    }
    if (amt < 1) {
        invoiceErrors.value.amount = 'Minimum deposit is $1.';
        return;
    }
    if (amt > 10000) {
        invoiceErrors.value.amount = 'Maximum deposit is $10,000.';
        return;
    }
    if (!selectedNetwork.value?.enabled) {
        invoiceErrors.value.coin = 'Please select USDT BEP20.';
        return;
    }

    invoicePosting.value = true;
    try {
        const csrf = document.querySelector('meta[name="csrf-token"]')?.content ?? '';
        const res  = await fetchTimeout(route('deposit.invoice.create'), {
            method: 'POST',
            credentials: 'same-origin',
            headers: {
                'Content-Type':     'application/json',
                'X-CSRF-TOKEN':     csrf,
                'X-Requested-With': 'XMLHttpRequest',
                'Accept':           'application/json',
            },
            body: JSON.stringify({
                amount:      amt,
                gateway_id:  invoiceGateway.value?.id,
                to_currency: selectedNetwork.value.value,
            }),
        }, 20000);

        const ct   = res.headers.get('content-type') ?? '';
        const data = ct.includes('application/json') ? await res.json() : {};

        if (!res.ok) {
            invoiceErrors.value = data.errors ?? { amount: data.message ?? 'Checkout creation failed. Please try again.' };
            return;
        }

        checkoutPayment.value = data.payment;
        checkoutStatus.value = data.payment?.status_label ?? 'Waiting for payment';
        amountModalOpen.value = false;
        startCountdown(data.payment?.expires_at);
        startCheckoutPolling(data.payment?.reference);
        refreshDeposits();
    } catch {
        invoiceErrors.value = { amount: 'Connection error. Please try again.' };
    } finally {
        invoicePosting.value = false;
